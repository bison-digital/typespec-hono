import { emitFile, NoTarget, resolvePath, type EmitContext, type Type } from "@typespec/compiler";
import type { EmittedService, InputLocation } from "typespec-http-zod";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { emitHttpZod } from "typespec-http-zod";
import { renderApp } from "./app.js";
import { resolveBasePath } from "./base-path.js";
import { reportDiagnostic } from "./lib.js";

/**
 * This emitter's entry point. **the whole of `typespec-http-zod`, plus one file**.
 *
 * **A project lists ONE emitter, and this is why.** The validators and the server share a naming
 * contract: `app.gen.ts` imports `readWidgetPath` and `readWidgetResponses` from `schemas.gen.js` by
 * name. Two separate TypeSpec emitters would each get their own `$onEmit` and their own registry, and
 * would have to arrive at identical identifiers by coincidence. Running the library here means it
 * mints the names, writes them, and hands them back, so agreement is structural rather than hoped
 * for.
 *
 * **It uses nothing `typespec-http-zod` does not export.** The package's `exports` map makes a deep
 * import impossible, so this file is the proof that the published API is sufficient to build a server
 * generator on. Anything it cannot do from here is a gap in that API, to be fixed there.
 */
/**
 * The declaration a diagnostic should point at: the operation the library collected the route from,
 * by its id, falling back to the service when it cannot be found.
 *
 * **Never by name, and never by verb and path.** A name never matched an operation declared inside
 * an `interface`, whose id carries the interface, so every diagnostic pointed at the service
 * namespace. Verb and path, which replaced it, are shared by every member of a `@sharedRoute`, so
 * each member's diagnostic pointed at the first of them.
 */
function targetFor(emitted: EmittedService, operationId: string): Type {
	return emitted.operations.get(operationId)?.operation ?? emitted.service.namespace;
}

/** How a `shared-input-key` refusal names where each of the two inputs comes from. */
const INPUT_LOCATION_NOUNS: Readonly<Record<InputLocation, string>> = {
	path: "path parameter",
	query: "query parameter",
	header: "header",
	cookie: "cookie",
	body: "body",
};

/** The header the emitted runtime carries, matching every other generated file. */
function generatedRuntimeBanner(hint: string | undefined): string {
	const second =
		hint === undefined
			? "// A copy of this package's runtime, emitted so the generated code imports no package at run time."
			: `// Regenerate with: ${hint}`;
	return `// GENERATED by typespec-hono. DO NOT EDIT.
${second}
`;
}

/**
 * The generated runtime lands beside the generated code, so nothing the emitter writes imports this
 * package at run time.
 *
 * An emitter is a build-time tool. `@typespec/openapi3` is a devDependency and its output imports
 * nothing, which is the shape a build-time tool should have. A runtime half shipped in the package
 * would force it to be a `dependency`, and `--save-dev` would fail at deploy and nowhere earlier.
 * Emitting the runtime removes the choice rather than documenting it.
 *
 * **Always this module.** `runtime-module` used to replace it, and that made an application own a
 * copy of generated logic - see the `runtime-module-removed` diagnostic.
 */
export { DEFAULT_RUNTIME_MODULE } from "./app.js";

/** Where this package's own runtime source lives, to be copied beside the generated code. */
const RUNTIME_SOURCE = fileURLToPath(new URL("../../src/runtime.ts", import.meta.url));

/**
 * Whether `runtime-module` is set, at the top level or for a service; each place is reported.
 *
 * **A refused option writes nothing**, as an option the compiler's own schema refuses does:
 * `invalid-schema` stops the compile before any emitter runs. Written anyway, the output replaced a
 * project's generated files with ones importing a runtime it had not moved to, from a compile that
 * failed.
 */
function refusesRuntimeModule(context: EmitContext): boolean {
	const options = context.options as Record<string, unknown> & {
		services?: Record<string, Record<string, unknown>>;
	};
	const values = [
		options["runtime-module"],
		...Object.values(options.services ?? {}).map((service) => service["runtime-module"]),
	].filter((value) => value !== undefined);
	for (const value of values) {
		reportDiagnostic(context.program, {
			code: "runtime-module-removed",
			format: { value: String(value) },
			target: NoTarget,
		});
	}
	return values.length > 0;
}

export async function $onEmit(context: EmitContext): Promise<void> {
	if (refusesRuntimeModule(context)) return;
	for (const emitted of await emitHttpZod(context)) {
		await emitFile(context.program, {
			path: resolvePath(emitted.outputDir, "runtime.gen.ts"),
			content: `${generatedRuntimeBanner(emitted.options.regenerateHint)}${readFileSync(RUNTIME_SOURCE, "utf8")}`,
		});
		/**
		 * **The path the DOCUMENT says this service is served under.** An OpenAPI path is relative to
		 * its server, so `@server("/api/v1")` plus `/accounts` publishes `/api/v1/accounts`. Mounting at
		 * the root made every client generated from the document 404.
		 */
		/**
		 * **A service this project does not serve still belongs in the program.**
		 *
		 * One compile is what makes a shared vocabulary shared, so a surface not yet served is in the
		 * spec for its types and its validators. Its server is not wanted, and without a way to say so
		 * the emitter would write an `app.gen.ts` that nothing mounts.
		 *
		 * Only this file is withheld. Everything the library emits for that service is untouched,
		 * because those are the reason it is in the program at all.
		 */
		const serviceName = emitted.service.namespace.name;
		if (context.options.services?.[serviceName]?.["emit-server"] === false) continue;
		const base = resolveBasePath(context.program, emitted.service.namespace);
		await emitFile(context.program, {
			path: resolvePath(emitted.outputDir, "app.gen.ts"),
			content: renderApp(
				emitted,
				{
					/**
					 * Reported rather than thrown, so a spec with one unmountable path still names every
					 * other problem in the same compile, and so the validators for the rest of the service
					 * are still written. A path this router cannot express is not a reason to emit nothing.
					 */
					unsupportedPathTemplate: (route, template, name) => {
						reportDiagnostic(context.program, {
							code: "unsupported-path-template",
							format: { template, name },
							target: targetFor(emitted, route.operationId),
						});
					},
					unvalidatedResponseMediaType: (route, status, types) => {
						reportDiagnostic(context.program, {
							code: "unvalidated-response-media-type",
							format: {
								operationId: route.operationId,
								status: String(status),
								types: types.join(", "),
							},
							target: targetFor(emitted, route.operationId),
						});
					},
					unvalidatedRequestMediaType: (route, types) => {
						reportDiagnostic(context.program, {
							code: "unvalidated-request-media-type",
							format: { operationId: route.operationId, types: types.join(", ") },
							target: targetFor(emitted, route.operationId),
						});
					},
					sharedInputKey: (route, shared) => {
						reportDiagnostic(context.program, {
							code: "shared-input-key",
							format: {
								operationId: route.operationId,
								first: INPUT_LOCATION_NOUNS[shared.first],
								key: shared.key,
								second: INPUT_LOCATION_NOUNS[shared.second],
							},
							target: targetFor(emitted, route.operationId),
						});
					},
					unvalidatableMediaType: (route, types) => {
						reportDiagnostic(context.program, {
							code: "unvalidatable-media-type",
							format: { operationId: route.operationId, types: types.join(", ") },
							target: targetFor(emitted, route.operationId),
						});
					},
				},
				base.basePaths,
			),
		});
	}
}
